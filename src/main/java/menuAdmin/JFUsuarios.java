    private void cargarUsuarios() {
        // Crear el modelo de la tabla con columnas
        DefaultTableModel modelo = new DefaultTableModel(new String[]{"ID", "Nombre", "Edad", "Rol", "Contraseña"}, 0);

        // Intentar conectarse a la base de datos
        try (Connection conn = Conexion.Conexion.getConexion();
             Statement st = conn.createStatement();
             ResultSet rs = st.executeQuery("SELECT * FROM usuario ORDER BY id")) {

            // Recorrer los resultados y agregarlos al modelo
            while (rs.next()) {
                modelo.addRow(new Object[]{
                    rs.getString("id"),
                    rs.getString("nombre"),
                    rs.getInt("edad"),       // Si edad es numérico
                    rs.getString("rol"),
                    rs.getString("contraseña")
                });
            }

            // Asignar el modelo a la tabla
            tablaUsuarios.setModel(modelo);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al cargar usuarios: " + e.getMessage());
        }
    }
    
