    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        String ID = txtID.getText();
        String nombre = txtNombre.getText();
        String edad = txtEdad.getText();
        String rol = cbxRol.getSelectedItem().toString();
        String password = txtPassword.getText();

        if (ID.isEmpty() || nombre.isEmpty() || edad.isEmpty() || rol.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete todos los campos.","Error",1);
            return;
        }else{
            if(esNumero(edad)){
                if(Integer.parseInt(edad) >= 18){
                    String sql = "INSERT INTO usuario(id, nombre, edad, rol, contraseña) VALUES (?, ?,?, ?,?)";
                    try (Connection conn = Conexion.Conexion.getConexion();
                         PreparedStatement ps = conn.prepareStatement(sql)) {
                        ps.setString(1, ID);
                        ps.setString(2, nombre);
                        ps.setInt(3, Integer.parseInt(edad));
                        ps.setString(4, rol);
                        ps.setString(5, password);
                        ps.executeUpdate();
                        JOptionPane.showMessageDialog(this, "Usuario agregado correctamente.");
                        cargarUsuarios();
                        limpiarCampos();
                    } catch (SQLException e) {
                        JOptionPane.showMessageDialog(this, "Error al agregar: " + e.getMessage());
                    }
                }else{
                    JOptionPane.showMessageDialog(this, "El valor ingresado en edad es invalido","Error",0);
                }
            }else{
                JOptionPane.showMessageDialog(this, "El valor ingresado en edad es invalido","Error",0);
            }
        }

        
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
        int fila = tablaUsuarios.getSelectedRow();
	if (fila < 0) {
            JOptionPane.showMessageDialog(this, "Seleccione una fila para editar.", "Error", JOptionPane.WARNING_MESSAGE);
            return;
	}

	String ID = txtID.getText();  // ID bloqueado, se usa para WHERE
	String nombre = txtNombre.getText();
	String edad = txtEdad.getText();
	String rol = cbxRol.getSelectedItem().toString();
	String password = txtPassword.getText();

        String sql = "UPDATE usuario SET nombre=?, edad=?, rol=?, contraseña=? WHERE id=?";
	try (Connection conn = Conexion.Conexion.getConexion();
	 PreparedStatement ps = conn.prepareStatement(sql)) {

	ps.setString(1, nombre);
	ps.setInt(2, Integer.parseInt(edad));
	ps.setString(3, rol);
	ps.setString(4, password);
	ps.setString(5, ID); // parámetro para WHERE

	ps.executeUpdate();

	JOptionPane.showMessageDialog(this, "Usuario actualizado correctamente.");
	cargarUsuarios(); // refrescar tabla
	limpiarCampos();  // limpiar formulario
	txtID.setEditable(true); // desbloquear ID para nuevo registro

	} catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al actualizar: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        int fila = tablaUsuarios.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(this, "Seleccione una fila para eliminar.", "Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String idSeleccionado = tablaUsuarios.getValueAt(fila, 1).toString();
        String usuarioActivo = lblUsuario.getText().replace("Usuario: ", ""); // obtener usuario en sesión

        // Evitar eliminar al usuario en sesión
        if (idSeleccionado.equals(usuarioActivo)) {
            JOptionPane.showMessageDialog(this, "No puedes eliminar el usuario que está en sesión.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Confirmar eliminación
        int confirm = JOptionPane.showConfirmDialog(this, "¿Está seguro de eliminar este usuario?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        // Ejecutar DELETE
        String id = (String) tablaUsuarios.getValueAt(fila, 0);
        String sql = "DELETE FROM usuario WHERE id=?";
        try (Connection conn = Conexion.Conexion.getConexion();
             PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, id);
            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Usuario eliminado correctamente.");
            cargarUsuarios();
            limpiarCampos();
            txtID.setEditable(true); // desbloquear ID para nuevo registro
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

